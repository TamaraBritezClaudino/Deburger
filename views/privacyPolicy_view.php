            <h2 id="aplicabilidad">1. Aplicabilidad y objeto de esta Política de Privacidad</h2>

            <p>
                Deburger es un servicio de venta y gestión de pedidos de productos
                gastronómicos. Esta Política de Privacidad se aplica al sitio web,
                sus formularios, sistema de pedidos y demás servicios que hagan
                referencia a esta política.
            </p>

            <p>
                El objetivo de esta política es informar a los usuarios sobre la
                forma en que Deburger recopila, utiliza, almacena y protege la
                información personal proporcionada durante el uso del sitio.
            </p>

            <p>
                Al utilizar los servicios de Deburger, el usuario acepta las
                condiciones establecidas en esta Política de Privacidad.
            </p>

            <h2 id="responsabilidad">2. Responsabilidad sobre el tratamiento de los datos</h2>

            <p>
                Deburger es responsable del tratamiento de los datos personales que
                los usuarios proporcionen mediante el sitio web, formularios de
                contacto, registro de usuarios y realización de pedidos.
            </p>

            <p>
                La información será utilizada únicamente para las finalidades
                indicadas en esta política y de acuerdo con la legislación aplicable.
            </p>

            <h2 id="recoleccion">3. Recolección de información</h2>

            <p>
                Deburger puede recopilar información proporcionada directamente por
                el usuario cuando utiliza el sitio, crea una cuenta, realiza un
                pedido o se comunica con el servicio de soporte.
            </p>

            <p>
                Entre los datos que pueden ser solicitados se encuentran:
            </p>

            <ul>
                <li>Nombre y apellido.</li>
                <li>Correo electrónico.</li>
                <li>Número de teléfono.</li>
                <li>Dirección de entrega.</li>
                <li>Información relacionada con los pedidos realizados.</li>
                <li>Método de pago seleccionado.</li>
            </ul>

            <p>
                También se pueden recopilar determinados datos técnicos relacionados
                con el uso del sitio, como el navegador utilizado, el dispositivo y
                la información necesaria para el correcto funcionamiento de la
                página.
            </p>

            <h2 id="finalidad">4. Finalidad del tratamiento de los datos</h2>

            <p>
                Deburger utiliza la información recopilada con las siguientes
                finalidades:
            </p>

            <ul>
                <li>Crear y administrar las cuentas de los usuarios.</li>
                <li>Procesar y gestionar los pedidos realizados.</li>
                <li>Coordinar la entrega de los productos.</li>
                <li>Contactar al usuario en relación con su pedido.</li>
                <li>Responder consultas realizadas al servicio de soporte.</li>
                <li>Mejorar el funcionamiento y la experiencia de uso del sitio.</li>
                <li>Mantener un registro de los pedidos realizados.</li>
                <li>Cumplir con las obligaciones legales correspondientes.</li>
            </ul>

            <h2 id="uso">5. Uso y conservación de la información</h2>

            <p>
                Deburger utilizará la información personal únicamente para cumplir
                con las finalidades indicadas en esta Política de Privacidad.
            </p>

            <p>
                Los datos podrán conservarse durante el tiempo necesario para
                gestionar la cuenta del usuario, procesar pedidos, mantener el
                historial de compras y cumplir con las obligaciones legales
                correspondientes.
            </p>

            <p>
                Deburger no venderá ni alquilará los datos personales de sus usuarios
                con fines comerciales.
            </p>

            <h2 id="cesion">6. Cesión de los datos personales</h2>

            <p>
                Deburger podrá compartir determinados datos personales únicamente
                cuando sea necesario para prestar correctamente el servicio, por
                ejemplo, con proveedores que participen en la gestión de pedidos o
                entregas.
            </p>

            <p>
                Los terceros que reciban información estarán obligados a utilizarla
                únicamente para la finalidad correspondiente y a mantener la
                confidencialidad de los datos.
            </p>

            <h2 id="seguridad">7. Confidencialidad y seguridad</h2>

            <p>
                Deburger adopta medidas razonables para proteger los datos personales
                de sus usuarios y evitar accesos, modificaciones, pérdidas o usos no
                autorizados.
            </p>

            <p>
                Sin embargo, debido a la naturaleza de Internet, ningún sistema puede
                garantizar una seguridad absoluta. Deburger se compromete a mantener
                medidas adecuadas para reducir los riesgos relacionados con el
                tratamiento de la información.
            </p>

            <h2 id="menores">8. Menores de edad</h2>

            <p>
                El uso de los servicios de Deburger por parte de menores de edad
                deberá realizarse con la autorización y supervisión de sus padres,
                tutores o responsables legales.
            </p>

            <p>
                Deburger recomienda a los responsables legales acompañar a los
                menores en el uso de servicios que requieran proporcionar datos
                personales.
            </p>

            <h2 id="derechos">9. Derechos de los usuarios</h2>

            <p>
                Los usuarios tienen derecho a conocer qué datos personales se
                encuentran registrados, solicitar su actualización o corrección y
                solicitar su eliminación cuando corresponda.
            </p>

            <p>
                Para realizar una solicitud relacionada con sus datos personales, el
                usuario puede comunicarse con Deburger mediante el correo electrónico
                indicado en la sección de Contacto.
            </p>

            <p>
                Las solicitudes serán evaluadas y respondidas de acuerdo con la
                legislación aplicable.
            </p>

            <h2 id="excepciones">10. Excepciones</h2>

            <p>
                Deburger podrá proporcionar información personal cuando sea necesario
                para cumplir con una obligación legal, responder a una orden judicial,
                proteger los derechos de los usuarios o prevenir actividades
                fraudulentas o ilegales.
            </p>

            <h2 id="modificacion">11. Modificación de la Política de Privacidad</h2>

            <p>
                Deburger podrá modificar esta Política de Privacidad cuando sea
                necesario para reflejar cambios en sus servicios, en la forma en que
                se utilizan los datos o en la legislación aplicable.
            </p>

            <p>
                Las modificaciones serán publicadas en esta misma sección. El uso
                continuado de los servicios después de la publicación de cambios
                implicará la aceptación de la política actualizada.
            </p>

